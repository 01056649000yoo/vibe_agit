const buildEntry = (id, right, wrong, category, explanation, examples, sourceType = 'dictionary') => ({
    id: `expansion-${id}`,
    question: `${right} / ${wrong}`,
    answer: right,
    searchable: [right, wrong],
    category,
    explanation,
    examples,
    sourceQuery: right,
    sourceType
});

const word = (id, right, wrong, meaning, examples) => buildEntry(
    id,
    right,
    wrong,
    '낱말 표기',
    `${meaning} ‘${wrong}’가 아니라 ‘${right}’로 적어요.`,
    examples
);

