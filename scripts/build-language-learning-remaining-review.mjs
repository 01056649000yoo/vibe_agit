const contentLevelFor = (item) => {
    const sourceId = Number(item.source.sourceId);
    if (PILOT_REMAINING[item.contentType].has(sourceId)) return 2;
    const levelFour = item.contentType === 'proverb' ? PROVERB_LEVEL_FOUR : IDIOM_LEVEL_FOUR;
    return levelFour.has(sourceId) ? 4 : 3;
};

const normalizedSimilarity = (left, right) => {
    const tokens = (value) => new Set(String(value).replaceAll(/[^가-힣 ]/g, ' ').split(/\s+/).filter((word) => word.length > 1));
    const leftTokens = tokens(left);
    const rightTokens = tokens(right);
    const intersection = [...leftTokens].filter((token) => rightTokens.has(token)).length;
    const union = new Set([...leftTokens, ...rightTokens]).size;
    return union === 0 ? 0 : intersection / union;
};

const definitionFor = (item) => {
    const sourceId = Number(item.source.sourceId);
    return item.contentType === 'proverb'
        ? (PROVERB_DEFINITION_OVERRIDES[sourceId] || item.definition)
        : (IDIOM_DEFINITION_OVERRIDES[sourceId] || item.definition);
};

const pickDistractors = (item, candidates, correctAnswer) => {
    const sourceId = Number(item.source.sourceId);
    const start = candidates.findIndex((candidate) => candidate.itemKey === item.itemKey);
    const picked = [];
    for (let step = 1; step < candidates.length && picked.length < 3; step += 1) {
        const candidate = candidates[(start + (step * 17) + sourceId) % candidates.length];
        const answer = definitionFor(candidate);
        if (candidate.itemKey !== item.itemKey
            && answer !== correctAnswer
            && !picked.includes(answer)
            && normalizedSimilarity(answer, correctAnswer) < 0.32) {
            picked.push(answer);
        }
    }
    if (picked.length !== 3) throw new Error(`${item.itemKey}의 서로 다른 오답 3개를 만들지 못했습니다.`);
    return picked;
};

const buildReviewItem = (item, candidates) => {
    const sourceId = Number(item.source.sourceId);
    const isProverb = item.contentType === 'proverb';
    const expression = isProverb
        ? (PROVERB_EXPRESSION_OVERRIDES[sourceId] || item.expression)
        : item.expression;
    const definition = definitionFor(item);
    const example = isProverb
        ? PROVERB_EXAMPLES[sourceId]
        : (IDIOM_EXAMPLE_OVERRIDES[sourceId] || item.example);
    if (!example) throw new Error(`${item.itemKey}의 예문이 없습니다.`);

    const correctAnswer = definition;
    const distractors = pickDistractors(item, candidates, correctAnswer);
    const correctIndex = (sourceId + (isProverb ? 1 : 3)) % 4;
    const choices = [...distractors];
    choices.splice(correctIndex, 0, correctAnswer);

    const reviewNotes = [];
    if (PROVERB_EXPRESSION_OVERRIDES[sourceId] && isProverb) {
        reviewNotes.push('원본 빈칸·정답을 대조해 완성 표현 초안을 바로잡음');
    }
    if (!isProverb && IDIOM_HANJA_CORRECTION_IDS.has(sourceId)) {
        reviewNotes.push('원본 파일 사이의 한자 이체자 표기를 대표 표기로 통일함');
    }

    return {
        itemKey: item.itemKey,
        expression,
        hanja: item.hanja,
        definition,
        example,
        contentLevel: contentLevelFor(item),
        meaningChoice: {
            choices,
            correctAnswer,
            explanation: definition
        },
        ...(reviewNotes.length > 0 ? { reviewNotes } : {})
    };
};

