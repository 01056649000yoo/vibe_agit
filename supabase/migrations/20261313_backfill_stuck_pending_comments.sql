-- 두 달 넘게 멈춰 있던 학생 댓글 108건 정리 (2026-09-18, 선생님 결정)
--
-- 무엇이 있었나:
--   `post_comments` 의 `pending` 108건이 2026-03-27 ~ 07-16 사이 것으로 남아 있었다.
--   7월 16일 이후로는 새로 생기지 않으니 원인은 이미 사라졌지만, 이 108건은 검사 대기표
--   (`comment_ai_review_slots`)에 들어 있지도 않아 **앞으로도 아무도 처리하지 않는** 상태였다.
--   아이는 친구 글에 댓글을 남겼는데 한 번도 친구에게 보이지 않았다.
--
-- 사람이 108건을 모두 읽고 판단했다(2026-09-18):
--   - 106건: 칭찬·격려·맞춤법 조언. 문제 없음 → 승인.
--   - 2건: 다른 아이 실명을 대며 계정을 해킹했다는 장난 1건, 친구를 이름으로 지목해 연애를
--     놀리는 말 1건 → 삭제. (내용은 아이 이름이 들어 있어 여기 옮기지 않는다. id 로만 가리킨다.)
--
-- ⚠️ 왜 트리거를 끄고 승인하나:
--   승인은 글 주인에게 "친구가 댓글 남겼어요" 알림을 만든다(`emit_feedback_comment_notification_v1`).
--   그대로 두면 **몇 달 지난 글에 대해 알림 102건이 한꺼번에** 아이들에게 간다.
--   알림이 가야 할 때는 이미 지났고 한꺼번에 터지는 쪽이 더 혼란스러우므로, 이 되메우기에서는
--   알림·발자국 트리거를 끄고 조용히 승인한다(`SET LOCAL` 이라 이 트랜잭션에서만 꺼진다).
--
-- 범위를 날짜로 묶는 이유: 적용 시점에 새로 들어온 `pending` 은 **정상적으로 AI 검사를 받아야 한다.**
-- 사람이 읽은 그때의 108건만 건드리도록 7월 17일 이전으로 잘랐다.

BEGIN;

-- 1) 선생님 판단으로 지우는 2건. 교사 화면의 [삭제] 와 같게 행을 지운다(되돌릴 수 없다).
DELETE FROM public.post_comments
WHERE id IN (
    'd675184a-e4d8-4f1c-b573-1950433431a5',
    '3d0d7c37-4343-429a-8079-6530a159d5a9'
)
AND status = 'pending';

-- 2) 나머지를 조용히 승인한다.
SET LOCAL session_replication_role = replica;

UPDATE public.post_comments
SET status = 'approved',
    moderated_at = NOW(),
    -- 'teacher'(교사 화면)·'ai'·'local_rule' 과 구분되는 표시. 운영자가 일괄 정리한 것이다.
    moderated_by = 'operator'
WHERE status = 'pending'
  AND created_at < TIMESTAMPTZ '2026-07-17 00:00:00+09';

COMMIT;
