-- 망가진 트래픽 기록 3일치를 비운다 (2026-08-21 ~ 2026-08-23).
--
-- 왜 비우나:
--   하루치 트래픽은 컨테이너 누적 바이트의 증가분인데, 기록 스크립트가 **전체 합계 하나로만**
--   견주었다. 배포할 때마다 agit-app 을 지우고 새로 만들어 그 컨테이너의 누적값이 0부터 다시
--   쌓이는데, 합계만 보면 이 사실이 보이지 않는다. 게다가 `docker stats` 가 값을 못 준 날에도
--   0 을 상태 파일에 적어 두어 다음 날 하루치가 통째로 잘못 들어갔다.
--
--   그 결과 남은 값:
--     2026-08-21  3.5MB / 5.3MB    — 하루치라기엔 지나치게 작다
--     2026-08-22  0 / 0            — 그날 값을 재지 못한 흔적
--     2026-08-23  1.29GB / 1.43GB  — 하루치가 아니라 컨테이너가 켜진 뒤 누적분 전체
--
--   셋 다 실제 하루 트래픽이 아니다. 화면에서 가장 큰 값이 세로 기준이 되므로, 두면 앞으로
--   쌓일 정상 값들이 바닥에 깔려 보이지 않는다. 없는 값은 `기록 없음`으로 보이는 편이 정직하다.
--
-- 무엇을 남기나:
--   같은 줄의 디스크 여유·DB 크기·컨테이너 수는 그때그때 잰 값이라 이 문제와 무관하다. 그대로 둔다.
--   기록 스크립트는 같은 날 다시 부르면 덮어쓰므로, 앞으로 다시 재면 이 자리는 채워진다.

BEGIN;

UPDATE public.system_daily_metrics
   SET rx_bytes = NULL,
       tx_bytes = NULL
 WHERE metric_day BETWEEN DATE '2026-08-21' AND DATE '2026-08-23'
   AND (rx_bytes IS NOT NULL OR tx_bytes IS NOT NULL);

COMMIT;
